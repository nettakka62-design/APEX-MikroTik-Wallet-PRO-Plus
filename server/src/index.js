require('dotenv').config();
const path=require('path');
const express=require('express');const helmet=require('helmet');const cors=require('cors');const rateLimit=require('express-rate-limit');
const app=express();
app.use(helmet({contentSecurityPolicy:false}));
app.use(cors({origin:process.env.APP_ORIGIN||'http://localhost:3000'}));
app.use(express.json({limit:'100kb'}));
app.use('/api',rateLimit({windowMs:15*60*1000,limit:300,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(_req,res)=>res.json({ok:true,service:'APEX MikroTik Wallet PRO+'}));
app.use('/api/auth',require('./routes/auth'));
app.use('/api/customers',require('./routes/customers'));
app.use('/api/renewals',require('./routes/renewals'));
app.use('/api/router',require('./routes/router'));
app.use(express.static(path.join(__dirname,'../../public')));
app.use((err,_req,res,_next)=>{console.error(err.message);const status=err.message==='MIKROTIK_NOT_CONFIGURED'?503:500;res.status(status).json({error:status===503?'MIKROTIK_NOT_CONFIGURED':'SERVER_ERROR'});});
const port=Number(process.env.PORT)||3000;app.listen(port,()=>console.log(`APEX running at http://localhost:${port}`));
